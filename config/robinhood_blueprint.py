class RobinhoodBlueprintError(RuntimeError):
    __slots__ = ("code", "record_id")

    def __init__(self, code: str, record_id: str | None = None) -> None:
        self.code = code
        self.record_id = record_id
        message = code if record_id is None else f"{code} record={record_id}"
        super().__init__(message)


